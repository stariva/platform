import { hatchet } from "../client";
import { mirrorSync } from "../lib/mirror";

/**
 * Каждый час копирует файлы мастер-классов из активного бакета в зеркало
 * (VK Cloud): видео, HLS-нарезки и PDF. Сайт сверяет листинги обоих бакетов
 * и выдаёт пачку с подписанными ссылками — чтение из активного, заливку в
 * зеркало; ключей от бакета у воркера нет. Воркер копирует пачку и снова
 * спрашивает, пока зеркало не догонит активный бакет или не выйдет бюджет
 * прогона (40 минут). Скопированное из выдачи пропадает, поэтому повтор
 * после сбоя ничего не дублирует.
 *
 * Пока зеркало не настроено на сайте, прогон тихо завершается. Первое
 * наполнение идёт несколько прогонов; чтобы догнать быстрее, поднимите
 * частоту cron и верните обратно, когда зеркало догонит.
 */
export const workshopStorageMirrorWorkflow = hatchet.workflow({
  name: "workshop-storage-mirror",
  on: { cron: "20 * * * *" },
});

workshopStorageMirrorWorkflow.task({
  name: "sync-workshop-files",
  retries: 3,
  executionTimeout: "50m",
  fn: () => mirrorSync(),
});
