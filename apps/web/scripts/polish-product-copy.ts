// Размеры в БД бывают вразнобой («46,42,44») — показываем по возрастанию
const sortSizes = (sizes: string[]) =>
  [...sizes].sort((a, b) => Number(a) - Number(b) || a.localeCompare(b));

// Материал из Ozon бывает в нижнем регистре или описанием вместо значения
const tidyMaterial = (value: string | null) => {
  if (!value) return value;
  const v = value.trim();
  if (/^сумки из шнура$/i.test(v)) return "Хлопковый шнур";
  if (/макраме из полиэфирного шнура/i.test(v)) return "Полиэфирный шнур";
  return v.charAt(0).toUpperCase() + v.slice(1);
};

const rows = await db.select().from(products);
let changed = 0;
const problems: string[] = [];

for (const row of rows) {
  const key = row.slug.slice(-4);
  const copy = COPY[key];
  if (!copy) {
    problems.push(`нет текстов для ${row.slug}`);
    continue;
  }
  if (copy.seoTitle.length > 52)
    problems.push(`${key}: seoTitle ${copy.seoTitle.length}`);
  if (copy.seoDescription.length < 100 || copy.seoDescription.length > 165) {
    problems.push(`${key}: seoDescription ${copy.seoDescription.length}`);
  }

  const patch = {
    name: copy.name,
    description:
      copy.description ??
      (copy.replace ?? []).reduce((html, [from, to]) => {
        if (!html.includes(from))
          problems.push(`${key}: нет фрагмента «${from}»`);
        return html.replace(from, to);
      }, cleanDescription(row.description)),
    material: copy.material ?? tidyMaterial(row.material) ?? "Хлопок",
    dimensions: copy.dimensions ?? row.dimensions,
    sizes: sortSizes(row.sizes),
    seoTitle: copy.seoTitle,
    seoDescription: copy.seoDescription,
  };

  console.log(`\n── ${row.slug}`);
  console.log(`  name:     ${row.name}\n         →  ${patch.name}`);
  if (patch.material !== row.material) {
    console.log(`  material: ${row.material} → ${patch.material}`);
  }
  if (patch.dimensions !== row.dimensions) {
    console.log(`  dims:     ${row.dimensions} → ${patch.dimensions}`);
  }
  console.log(
    `  desc:     ${row.description.length} → ${patch.description.length} симв.`,
  );
  if (process.argv.includes("--show-desc")) console.log(patch.description);

  if (apply) {
    await db.update(products).set(patch).where(eq(products.id, row.id));
  }
  changed++;
}

console.log(
  `\n${apply ? "Записано" : "Будет изменено"}: ${changed} из ${rows.length}`,
);
if (problems.length) console.log(["Проблемы:", ...problems].join("\n"));
process.exit(problems.length ? 1 : 0);
